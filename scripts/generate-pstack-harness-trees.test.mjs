import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { SourceTextModule, SyntheticModule, createContext } from "node:vm";

const url = new URL("./generate-pstack-harness-trees.mjs", import.meta.url);
const filename = fileURLToPath(url);
const source = readFileSync(url, "utf8");

// Execute the complete production check against the real source/generated
// trees. Only the native path separator boundary varies; filesystem calls,
// rendering, generated bytes and drift detection are all production code.
async function checkTree(windowsPaths) {
  const output = [];
  const context = createContext({
    Buffer,
    console: { log: (...args) => output.push(args.join(" ")) },
    process: {
      argv: [process.execPath, filename, "--check"],
      exit: (code) => { throw new Error(`generator exited ${code}: ${output.join("\n")}`); },
    },
  });
  const main = new SourceTextModule(source, {
    context, identifier: url.href,
    initializeImportMeta: (meta) => { meta.url = url.href; },
  });
  await main.link(async (specifier) => {
    const imported = await import(specifier);
    const exports = { ...imported };
    if (specifier === "node:path" && windowsPaths) {
      exports.relative = path.win32.relative;
      exports.sep = path.win32.sep;
    }
    return new SyntheticModule(Object.keys(exports), function () {
      for (const [name, value] of Object.entries(exports)) this.setExport(name, value);
    }, { context });
  });
  await main.evaluate();
  assert.deepEqual(output, ["harness/pstack is up to date."]);
}

test("generated tree checks with native relative path keys", () => checkTree(false));
test("generated tree checks with Windows relative path keys", () => checkTree(true));
