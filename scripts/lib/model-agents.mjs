import { mkdir, readFile, writeFile, rename, unlink } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { randomUUID } from "node:crypto";
import { resolveRole } from "./pstack-config.mjs";

export async function setupModelAgents({ config, runtime, role, catalog, scope, repo = process.cwd(), home = process.env.HOME, pluginRoot }) {
  if (!["user", "repo"].includes(scope)) throw new Error("agents requires scope user or repo");
  if (!["vscode-local", "vscode-copilot", "copilot-cli"].includes(runtime)) {
    throw new Error("Model-agent generation supports Copilot and Local only; use the other client's live selector.");
  }
  if (runtime === "vscode-local" && scope === "user") {
    throw new Error("Local user agents use VS Code profile storage. Use scope repo or Chat: New Custom Agent.");
  }
  if (scope === "user" && !home) throw new Error("User agent generation requires a home directory");
  const selection = resolveRole(config, role, { runtime, catalog });
  const members = selection.members ?? [selection];
  if (members.some(member => member.inherited || !member.model)) {
    throw new Error("Named-model agent generation requires resolved explicit identities; inheritance must use the ordinary host agent.");
  }
  const dir = scope === "repo" ? resolve(repo, ".github/agents") : resolve(home, ".copilot/agents");
  const pending = [];
  const results = [];
  const marker = "<!-- Generated by pstack model setup. -->";
  for (const [index, member] of members.entries()) {
    const name = `pstack-${role}${members.length > 1 ? `-${index + 1}` : ""}`;
    const path = resolve(dir, `${name}.agent.md`);
    const tools = ["exploration", "architecture", "explanation", "review"].includes(role)
      ? ["read", "search"] : ["read", "search", "edit", "execute"];
    const controls = member.controls;
    if (controls.speed) {
      throw new Error("Agent files have no portable speed control. Remove speed for this role or use a supported live task selector.");
    }
    const local = runtime === "vscode-local";
    if (local && controls.reasoningEffort) {
      throw new Error("Local agent files do not expose a portable reasoning-effort field. Use a supported live tool selector.");
    }
    const header = `---\nname: ${name}\ndescription: "Use for the explicitly configured pstack ${role} role."\nmodel: ${JSON.stringify(member.model.id)}\ntools: ${JSON.stringify(tools)}\n`;
    const policy = local ? "" : `model-policy: required\nstrict-tools-list: true\ninclude-custom-instructions: true\n${controls.reasoningEffort ? `reasoning-effort: ${JSON.stringify(controls.reasoningEffort)}\n` : ""}`;
    const text = `${header}${policy}---\n\n${marker}\n\nRead ${JSON.stringify(resolve(pluginRoot, "docs/core.md"))} and the active client adapter before work.\nThe required configured identity is ${JSON.stringify(member.model.id)} (${member.model.family ?? "unknown family"}).\nIf the host cannot enforce that choice, stop. Return evidence and limitations; do not invent execution metadata.\n${tools.length === 2 ? "Read/search only. Do not execute tests or edit; return hypotheses for the parent to verify." : "Make scoped changes and run project verification. Do not delegate or perform unauthorized external writes."}\n`;
    let current;
    try {
      current = await readFile(path, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (current && !current.includes(marker)) throw new Error(`Refusing to overwrite unrelated agent ${path}`);
    pending.push({ name, path, text, current, member, controls, tools });
  }
  for (const { name, path, text, current, member, controls, tools } of pending) {
    if (current !== text) {
      await mkdir(dirname(path), { recursive: true });
      const temp = `${path}.${randomUUID()}.pending`;
      try {
        await writeFile(temp, text, { mode: 0o600, flag: "wx" });
        await rename(temp, path);
      } finally {
        await unlink(temp).catch(error => { if (error.code !== "ENOENT") throw error; });
      }
    }
    results.push({ name, path, changed: current !== text, model: member.model, controls, tools });
  }
  return {
    agents: results, warnings: selection.warnings,
    limitation: runtime === "vscode-copilot" ? "VS Code conversion may not forward required-model or strict-tools policy. Verify native loading and effective permissions; otherwise stop strict panels." : "Restart and verify effective model and tools in the host before execution.",
  };
}
